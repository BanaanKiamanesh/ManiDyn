end


function testURDFJointDynamicsAreExtracted(TestCase)
    URDFPath = fullfile(TestCase.TestData.URDFFolder, 'damped_revolute.urdf');
    Actual = DynStruct(URDFPath);

    TestCase.verifyEqual(Actual.Mass, 1);
    TestCase.verifyEqual(Actual.Length, 1);
    TestCase.verifyEqual(Actual.Radius, 0.1);
    TestCase.verifyEqual(Actual.Fv, 0.25);
    TestCase.verifyEqual(Actual.Fc, 0.4);
    TestCase.verifyEqual(Actual.COM, [-0.5, 0, 0], 'AbsTol', 1e-12);
    TestCase.verifyEqual(Actual.DH.a, 1, 'AbsTol', 1e-12);
    TestCase.verifyEqual(Actual.DH.type, 'r');
end


function testRealRobotURDFIsAcceptedDirectlyByModels(TestCase)
    URDFPath = fullfile(TestCase.TestData.URDFFolder, 'scara.urdf');
    Dynamics = ManipulatorDynamics(URDFPath);
    Kinematics = ManipulatorKinematics(URDFPath);

    TestCase.verifyClass(Dynamics, 'ManipulatorDynamics');
    TestCase.verifyClass(Kinematics, 'ManipulatorKinematics');
end


function testDirectURDFInputMatchesStructureInput(TestCase)
    URDFPath = fullfile(TestCase.TestData.URDFFolder, 'damped_revolute.urdf');
    Parameters = DynStruct(URDFPath);
    Q = 0.2;

    KinematicsFromURDF = ManipulatorKinematics(string(URDFPath));
    KinematicsFromDH = ManipulatorKinematics(Parameters.DH);
    FKFromURDF = KinematicsFromURDF.CalculateFK('Return', 'handle');
    FKFromDH = KinematicsFromDH.CalculateFK('Return', 'handle');
    TestCase.verifyEqual(FKFromURDF(Q), FKFromDH(Q), 'AbsTol', 1e-12);

    DynamicsFromURDF = ManipulatorDynamics(URDFPath);
    DynamicsFromStruct = ManipulatorDynamics(Parameters);
    BFromURDF = DynamicsFromURDF.MassMatrix('Return', 'handle');
    BFromStruct = DynamicsFromStruct.MassMatrix('Return', 'handle');
    TestCase.verifyEqual(BFromURDF(Q), BFromStruct(Q), 'AbsTol', 1e-12);
end


