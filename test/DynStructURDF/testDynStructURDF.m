end


function testDirectParameterInterfaceRemainsSupported(TestCase)
    DH = DHStruct('alpha', [0, 0], 'a', [1, 1], 'd', [0, 0], ...
        'theta', [0, 0], 'type', 'rr');
    Actual = DynStruct( ...
        'Mass', [1, 2], ...
        'Inertia', {eye(3), 2 * eye(3)}, ...
        'COM', [0.5, 0, 0; 0.25, 0, 0], ...
        'DH', DH);

    TestCase.verifyEqual(Actual.Mass, [1, 2]);
    TestCase.verifyEqual(Actual.Fv, [0, 0]);
    TestCase.verifyEqual(Actual.Fc, [0, 0]);
    TestCase.verifyEqual(Actual.DH, DH);
end


function verifyParameters(TestCase, Actual, Expected)
    NumericFields = {'Mass', 'Length', 'Radius', 'COM'};
    for k = 1:numel(NumericFields)
        Field = NumericFields{k};
        TestCase.verifyEqual(Actual.(Field), Expected.(Field), ...
            'AbsTol', 1e-9, 'RelTol', 1e-8);
    end

    DHFields = {'alpha', 'a', 'd', 'theta'};
    for k = 1:numel(DHFields)
        Field = DHFields{k};
        TestCase.verifyEqual(Actual.DH.(Field), Expected.DH.(Field), ...
            'AbsTol', 1e-9, 'RelTol', 1e-8);
    end
    TestCase.verifyEqual(Actual.DH.type, Expected.DH.type);
    TestCase.verifyEqual(Actual.DH.notation, 'original');
    TestCase.verifyEqual(Actual.Fv, zeros(size(Actual.Mass)));
    TestCase.verifyEqual(Actual.Fc, zeros(size(Actual.Mass)));

    TestCase.verifyEqual(numel(Actual.Inertia), numel(Expected.Inertia));
    for k = 1:numel(Actual.Inertia)
        TestCase.verifyEqual(Actual.Inertia{k}, Expected.Inertia{k}, ...
            'AbsTol', 1e-9, 'RelTol', 1e-8);
        TestCase.verifyEqual(Actual.Inertia{k}, Actual.Inertia{k}.', ...
            'AbsTol', 1e-12);
        TestCase.verifyGreaterThanOrEqual(min(eig(Actual.Inertia{k})), -1e-12);
    end
end


