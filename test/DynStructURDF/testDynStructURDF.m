function Tests = testDynStructURDF
    %TESTDYNSTRUCTURDF Tests dynamic-parameter extraction from URDF files.
    Tests = functiontests(localfunctions);
end


function setupOnce(TestCase)
    TestFolder = fileparts(mfilename('fullpath'));
    ProjectRoot = fileparts(fileparts(TestFolder));
    addpath(fullfile(ProjectRoot, 'src'));
    addpath(genpath(fullfile(ProjectRoot, 'utils')));
    TestCase.TestData.ProjectRoot = ProjectRoot;
    TestCase.TestData.URDFFolder = fullfile(TestFolder, 'urdfs');
end


function testSCARAKinovaUR10AgainstActualValues(TestCase)
    Names = {'scara', 'ur10', 'kinova_gen3'};

    for k = 1:numel(Names)
        URDFPath = fullfile(TestCase.TestData.URDFFolder, [Names{k}, '.urdf']);
        Actual = DynStruct(URDFPath);
        Expected = referenceParameters(Names{k});
        verifyParameters(TestCase, Actual, Expected);
    end
end


function testNameValueURDFAndFrictionOverride(TestCase)
    URDFPath = fullfile(TestCase.TestData.URDFFolder, 'scara.urdf');
    Fv = [0.1, 0.2, 0.3, 0.4];
    Fc = [1, 2, 3, 4];
    Actual = DynStruct('URDF', URDFPath, 'Fv', Fv, 'Fc', Fc);

    TestCase.verifyEqual(Actual.Fv, Fv);
    TestCase.verifyEqual(Actual.Fc, Fc);
    TestCase.verifyEqual(Actual.DH.type, 'rrpr');
end


function testBundledKinovaExampleURDF(TestCase)
    URDFPath = fullfile(TestCase.TestData.ProjectRoot, ...
        'examples', 'Kinova Gen3', 'WithURDF', 'urdf', 'kinova_gen3.urdf');
    Actual = DynStruct(URDFPath);
    Expected = referenceParameters('kinova_gen3');
